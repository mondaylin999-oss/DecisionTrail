/**
 * The visual language that keeps facts, AI interpretation and privacy visible.
 * Every mark uses an icon AND text so meaning never depends on colour alone.
 */
import type { FieldOrigin, MatchLabel } from "@/lib/types";
import { label as human, type OutcomeCategory, type OutcomeStatus, type PrivacyMode } from "@/lib/vocab";
import { Badge } from "./ui";

export function InferenceBadge({ where }: { where: "ON_DEVICE" | "IN_CLOUD" | null | undefined }) {
  if (!where) return null;
  return where === "ON_DEVICE" ? (
    <Badge className="border-accent bg-subtle text-accent" title="This AI output was generated by Gemini Nano on your device">
      Ran on this device
    </Badge>
  ) : (
    <Badge className="border-accent bg-subtle text-accent" title="This AI output was generated by cloud Gemini through Firebase AI Logic">
      Ran in the cloud
    </Badge>
  );
}

export function OriginChip({ origin }: { origin: FieldOrigin | undefined }) {
  if (origin === "ai_extracted")
    return <Badge className="border-line bg-subtle text-accent" title="Suggested by AI. Check it">AI-suggested</Badge>;
  if (origin === "user_added") return <Badge className="border-line bg-subtle text-ink">You added</Badge>;
  if (origin === "user_confirmed") return <Badge className="border-line bg-surface text-ink">You confirmed</Badge>;
  return null;
}

const matchStyles: Record<MatchLabel, string> = {
  strong: "border-accent bg-subtle text-accent",
  partial: "border-signal bg-signal-soft text-signal",
  weak: "border-line bg-subtle text-muted",
};

export function MatchBadge({ label }: { label: MatchLabel }) {
  return <Badge className={matchStyles[label]}>{human(label)} contextual match</Badge>;
}

const outcomeStyles: Record<string, string> = {
  positive: "border-accent text-accent",
  achieved: "border-accent text-accent",
  negative: "border-signal text-signal",
  not_achieved: "border-signal text-signal",
  mixed: "border-signal text-signal",
  partially_achieved: "border-signal text-signal",
  reversed: "border-line text-muted",
};

export function OutcomeChip({ value }: { value: OutcomeCategory | OutcomeStatus | null | undefined }) {
  if (!value) return <Badge className="border-line text-muted">Outcome not yet recorded</Badge>;
  return <Badge className={outcomeStyles[value] ?? "border-line text-muted"}>{"Outcome: "} {human(value)}</Badge>;
}

export function DemoBadge() {
  return <Badge className="border-signal bg-signal-soft text-signal">DEMO DATA</Badge>;
}

export function PrivacyPill({ mode }: { mode: PrivacyMode }) {
  const map = {
    private: { t: "Private", c: "border-accent bg-subtle text-accent", d: "AI runs only on your device" },
    hybrid: { t: "Hybrid", c: "border-signal bg-signal-soft text-signal", d: "On-device first; cloud fallback allowed for structuring" },
    cloud_research: { t: "Cloud Research", c: "border-accent bg-subtle text-accent", d: "Hybrid + consented live web research" },
  }[mode];
  return <Badge className={map.c} title={map.d}>{map.t}</Badge>;
}

export function AiText({ children }: { children: React.ReactNode }) {
  return (
    <p className="ai-text text-sm text-ink">
      <span className="sr-only">{"AI interpretation: "}</span>
      {children}
    </p>
  );
}
