/**
 * The visual language that keeps facts, AI interpretation and privacy visible.
 * Every mark uses an icon AND text so meaning never depends on colour alone.
 */
import type { FieldOrigin, MatchLabel } from "@/lib/types";
import { label as human, type OutcomeCategory, type OutcomeStatus, type PrivacyMode } from "@/lib/vocab";
import { useLanguage } from "@/lib/i18n";
import { Badge } from "./ui";

export function InferenceBadge({ where }: { where: "ON_DEVICE" | "IN_CLOUD" | null | undefined }) {
  if (!where) return null;
  return where === "ON_DEVICE" ? (
    <Badge className="border-emerald-300 bg-emerald-50 text-emerald-800" title="This AI output was generated by Gemini Nano on your device">
      🔒 ON_DEVICE
    </Badge>
  ) : (
    <Badge className="border-sky-300 bg-sky-50 text-sky-800" title="This AI output was generated by cloud Gemini through Firebase AI Logic">
      ☁️ IN_CLOUD
    </Badge>
  );
}

export function OriginChip({ origin }: { origin: FieldOrigin | undefined }) {
  if (origin === "ai_extracted")
    return <Badge className="border-violet-300 bg-violet-50 text-violet-800" title="Suggested by AI. Check it">✨ AI-suggested</Badge>;
  if (origin === "user_added") return <Badge className="border-slate-300 bg-slate-50 text-slate-700">👤 You added</Badge>;
  if (origin === "user_confirmed") return <Badge className="border-slate-300 bg-white text-slate-700">✓ You confirmed</Badge>;
  return null;
}

const matchStyles: Record<MatchLabel, string> = {
  strong: "border-emerald-300 bg-emerald-50 text-emerald-800",
  partial: "border-amber-300 bg-amber-50 text-amber-800",
  weak: "border-slate-300 bg-slate-50 text-slate-600",
};

export function MatchBadge({ label }: { label: MatchLabel }) {
  const { t } = useLanguage();
  return <Badge className={matchStyles[label]}>{label === "strong" ? "●" : label === "partial" ? "◐" : "○"} {t(human(label))} {t("contextual match")}</Badge>;
}

const outcomeStyles: Record<string, string> = {
  positive: "border-emerald-300 text-emerald-800",
  achieved: "border-emerald-300 text-emerald-800",
  negative: "border-red-300 text-red-800",
  not_achieved: "border-red-300 text-red-800",
  mixed: "border-amber-300 text-amber-800",
  partially_achieved: "border-amber-300 text-amber-800",
  reversed: "border-purple-300 text-purple-800",
};

export function OutcomeChip({ value }: { value: OutcomeCategory | OutcomeStatus | null | undefined }) {
  const { t } = useLanguage();
  if (!value) return <Badge className="border-slate-300 text-slate-500">Outcome not yet recorded</Badge>;
  return <Badge className={outcomeStyles[value] ?? "border-slate-300 text-slate-600"}>{t("Outcome: ")} {t(human(value))}</Badge>;
}

export function DemoBadge() {
  return <Badge className="border-orange-300 bg-orange-50 text-orange-800">DEMO DATA</Badge>;
}

export function PrivacyPill({ mode }: { mode: PrivacyMode }) {
  const map = {
    private: { t: "🔒 Private", c: "border-emerald-400 bg-emerald-50 text-emerald-800", d: "AI runs only on your device" },
    hybrid: { t: "⇄ Hybrid", c: "border-amber-400 bg-amber-50 text-amber-800", d: "On-device first; cloud fallback allowed for structuring" },
    cloud_research: { t: "☁️ Cloud Research", c: "border-sky-400 bg-sky-50 text-sky-800", d: "Hybrid + consented live web research" },
  }[mode];
  return <Badge className={map.c} title={map.d}>{map.t}</Badge>;
}

export function AiText({ children }: { children: React.ReactNode }) {
  const { t } = useLanguage();
  return (
    <p className="ai-text text-sm text-slate-700">
      <span className="sr-only">{t("AI interpretation: ")}</span>
      {children}
    </p>
  );
}
