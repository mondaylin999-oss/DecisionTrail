"use client";
import { useSearchParams } from "next/navigation";
import { Suspense, useEffect, useMemo, useState } from "react";
import { PageTitle } from "@/components/AppShell";
import { useAuth } from "@/components/AuthProvider";
import { OutcomeChip } from "@/components/marks";
import { Badge, Card, CardTitle, Notice, Select, Spinner } from "@/components/ui";
import { api } from "@/lib/api";
import { CATEGORIES, OUTCOME_CATEGORIES, label, type OutcomeCategory } from "@/lib/vocab";
import { useLanguage } from "@/lib/i18n";

interface Source { id: string; url: string; publisher: string; sourceType: string; publishedAt: string | null; retrievedAt: string }
interface Claim { id: string; claimType: string; claimText: string; statedOrInferred: string; provenanceClass: string; sources: { sourceId: string; support: string; locator: string }[] }
interface Case {
  id: string;
  slug: string;
  title: string;
  category: string;
  decisionType: string;
  actorName: string;
  decisionDate: string | null;
  datePrecision: string;
  context: string;
  alternativesDocumented: string | null;
  decisionMade: string;
  reasonDocumented: string | null;
  observedOutcome: string;
  outcomeCategory: OutcomeCategory;
  observationPeriod: string;
  lessons: string;
  limitations: string;
  evidenceClassification: string;
  lastVerifiedAt: string;
  sources: Source[];
  claims: Claim[];
}

export default function ExplorerPage() {
  return (
    <Suspense fallback={<Spinner />}>
      <Explorer />
    </Suspense>
  );
}

function Explorer() {
  const { me } = useAuth();
  const { language, t } = useLanguage();
  const focus = useSearchParams().get("case");
  const [cases, setCases] = useState<Case[] | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [cat, setCat] = useState("all");
  const [outcome, setOutcome] = useState("all");
  const [open, setOpen] = useState<string | null>(focus);

  useEffect(() => {
    if (!me) return;
    api<{ cases: Case[] }>("/api/cases").then((r) => setCases(r.cases)).catch((e) => setErr(String(e.message ?? e)));
  }, [me]);

  const shown = useMemo(() => (cases ?? []).filter((c) => (cat === "all" || c.category === cat) && (outcome === "all" || c.outcomeCategory === outcome)), [cases, cat, outcome]);

  return (
    <>
      <PageTitle title="Historical explorer" subtitle="Curated, source-checked decisions, including failures and reversals. Classification describes where a claim comes from, not whether it is true." />
      {err && <Notice tone="error">{err}</Notice>}
      <div className="flex gap-2">
        <Select className="max-w-xs" options={["all", ...CATEGORIES]} labels={(v) => (v === "all" ? "All categories" : label(v))} value={cat} onChange={(e) => setCat(e.target.value)} />
        <Select className="max-w-xs" options={["all", ...OUTCOME_CATEGORIES]} labels={(v) => (v === "all" ? "All outcomes" : label(v))} value={outcome} onChange={(e) => setOutcome(e.target.value)} />
      </div>
      {cases && cases.length === 0 && (
        <Notice tone="info">{t("The curated library is empty. Add verified cases under data/cases/ (see _TEMPLATE.json) and run npm run db:seed-cases. Cases are never generated by AI.")}</Notice>
      )}
      <div className="space-y-3">
        {shown.map((c) => (
          <Card key={c.id} className="space-y-2">
            <button className="w-full text-left" onClick={() => setOpen(open === c.id ? null : c.id)} aria-expanded={open === c.id}>
              <div className="flex flex-wrap items-center gap-2">
                <OutcomeChip value={c.outcomeCategory} />
                <Badge className="border-slate-300 text-slate-600">{t(label(c.category))}</Badge>
                <Badge className="border-slate-300 text-slate-600">{t("Evidence:")} {t(label(c.evidenceClassification))}</Badge>
              </div>
              <h3 className="mt-1 font-semibold">{c.title}</h3>
              <p className="text-xs text-slate-500">
                {c.actorName} · {c.decisionDate ? (c.datePrecision === "year" ? c.decisionDate.slice(0, 4) : new Date(c.decisionDate).toLocaleDateString(language === "my" ? "my-MM" : "en-US")) : t("date not established")} · {t("last verified")} {new Date(c.lastVerifiedAt).toLocaleDateString(language === "my" ? "my-MM" : "en-US")}
              </p>
            </button>
            {open === c.id && (
              <div className="space-y-3 border-t border-slate-200 pt-3 text-sm">
                <KV k={t("Context")} v={c.context} />
                <KV k={t("Alternatives considered")} v={c.alternativesDocumented ?? t("Not documented")} />
                <KV k={t("Decision")} v={c.decisionMade} />
                <KV k={t("Documented reason")} v={c.reasonDocumented ?? t("Not documented")} />
                <KV k={t("Observed outcome") + (c.observationPeriod ? ` (${c.observationPeriod})` : "")} v={c.observedOutcome} />
                <KV k={t("Lessons and implications")} v={c.lessons} />
                <KV k={t("Limitations")} v={c.limitations} />
                <div>
                  <CardTitle>{t("Claims and their sources")}</CardTitle>
                  <ul className="space-y-2">
                    {c.claims.map((cl) => (
                      <li key={cl.id}>
                        <Badge className="mr-1 border-slate-300 text-slate-600">{t(label(cl.claimType))}</Badge>
                        <span className={cl.statedOrInferred === "inferred" ? "ai-text" : undefined}>{cl.claimText}</span>{" "}
                        <span className="text-xs text-slate-500">({t(label(cl.provenanceClass))})</span>
                        {cl.sources.some((s) => s.support === "contradicts") && <Badge className="ml-1 border-red-300 text-red-700">Sources disagree</Badge>}
                        {cl.sources.map((s) => {
                          const src = c.sources.find((x) => x.id === s.sourceId);
                          return src ? (
                            <a key={s.sourceId} href={src.url} target="_blank" rel="noreferrer noopener" className="ml-1 rounded bg-slate-100 px-1.5 text-xs hover:underline">
                              📄 {src.publisher}
                              {s.support !== "supports" ? ` (${s.support})` : ""}
                            </a>
                          ) : null;
                        })}
                      </li>
                    ))}
                  </ul>
                </div>
              </div>
            )}
          </Card>
        ))}
      </div>
    </>
  );
}

function KV({ k, v }: { k: string; v: string }) {
  return (
    <div>
      <div className="text-xs font-medium uppercase text-slate-500">{k}</div>
      <p>{v || "—"}</p>
    </div>
  );
}
